char *bppc_trim(char *str) {
    char *end;
    while (runtime_isspace((unsigned char)*str)) str++;
    if (*str == 0) return str;
    end = str + runtime_strlen(str) - 1;
    while (end > str && runtime_isspace((unsigned char)*end)) end--;
    end[1] = '\0';
    return str;
}

bool bppc_parse_line_number(const char *str, int *out_line, const char **out_text) {
    while (*str && runtime_isspace((unsigned char)*str)) str++;
    if (!runtime_isdigit((unsigned char)*str)) return false;
    char *endptr;
    long val = runtime_strtol(str, &endptr, 10);
    *out_line = (int)val;
    *out_text = endptr;
    return true;
}

char *bppc_strdup(const char *src) {
    if (!src) return NULL;
    size_t len = runtime_strlen(src);
    char *dest = (char *)runtime_calloc(1, len + 1);
    if (dest) runtime_memcpy(dest, src, len + 1);
    return dest;
}

char *bppc_read_file_to_string(const char *path) {
    void *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (sz < 0) {
        fclose(f);
        return NULL;
    }
    char *buf = (char *)runtime_calloc(1, sz + 1);
    if (!buf) {
        fclose(f);
        return NULL;
    }
    if (sz > 0) {
        size_t rd = fread(buf, 1, sz, f);
        buf[rd] = '\0';
    }
    fclose(f);
    return buf;
}


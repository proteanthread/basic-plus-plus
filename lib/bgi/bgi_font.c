/* ======================================================================
 * Text Rendering
 * ====================================================================== */

void BGI_outtextxy(BGI_Context *ctx, int x, int y, const char *text) {
    if (!ctx || !ctx->framebuffer || !text) return;

    int color = ctx->fg_color;
    int bg = ctx->bg_color;
    int scale = ctx->text_size;
    if (scale < 1) scale = 1;
    int cell_w = 8 * scale;
    int cell_h = 8 * scale;

    int cur_x = x;
    int cur_y = y;

    while (*text) {
        unsigned char ch = (unsigned char)*text;

        const uint8_t *glyph = bgi_font_8x8[ch];

        /* Render glyph pixel by pixel */
        for (int row = 0; row < 8; ++row) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; ++col) {
                int pixel_on = (bits >> (7 - col)) & 1;
                int c = pixel_on ? color : bg;

                if (ctx->text_direction == 0) {
                    /* Horizontal */
                    for (int sy = 0; sy < scale; ++sy) {
                        for (int sx = 0; sx < scale; ++sx) {
                            BGI_putpixel(ctx,
                                cur_x + col * scale + sx,
                                cur_y + row * scale + sy,
                                c);
                        }
                    }
                } else {
                    /* Vertical (90 degrees CW rotation) */
                    for (int sy = 0; sy < scale; ++sy) {
                        for (int sx = 0; sx < scale; ++sx) {
                            BGI_putpixel(ctx,
                                cur_x + row * scale + sx,
                                cur_y - col * scale - sy,
                                c);
                        }
                    }
                }
            }
        }

        if (ctx->text_direction == 0) {
            cur_x += cell_w;
        } else {
            cur_y -= cell_h;
        }

        text++;
    }

    /* Update current position */
    ctx->cp_x = cur_x;
    ctx->cp_y = cur_y;
}

void BGI_settextstyle(BGI_Context *ctx, int font, int direction, int size) {
    if (!ctx) return;
    ctx->text_font = font;
    ctx->text_direction = direction;
    ctx->text_size = (size < 1) ? 1 : size;
}

int BGI_textwidth(const BGI_Context *ctx, const char *text) {
    if (!ctx || !text) return 0;
    int len = 0;
    while (text[len]) len++;
    int scale = ctx->text_size;
    if (scale < 1) scale = 1;
    return len * 8 * scale;
}

int BGI_textheight(const BGI_Context *ctx, const char *text) {
    (void)text;
    if (!ctx) return 0;
    int scale = ctx->text_size;
    if (scale < 1) scale = 1;
    return 8 * scale;
}

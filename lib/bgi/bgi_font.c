/**
 * @file bgi_font.c
 * @brief BGI Font System — Built-in 8x8 CP437 bitmap font and text rendering.
 *
 * SECTION 1: WHAT IT DOES, WHY IT EXISTS, AND WHY IT WORKS THIS WAY
 * - What it does: Provides bitmap text rendering for BGI graphics modes using
 *   an embedded 8x8 CP437 glyph table. Renders text via BGI_putpixel() calls.
 *   Includes character set mapping tables for PETSCII, ATASCII, and TRSCII.
 * - Why it exists: Enables text output in pure software graphics modes without
 *   any external font files or OS font services.
 * - Why it works this way: The font data is a static const array of 256 glyphs,
 *   each 8 bytes (8 rows of 8 pixels). This is the standard IBM PC BIOS font
 *   format. Character mapping tables translate alternate charsets to CP437
 *   glyph indices for rendering.
 *
 * SECTION 2: DEVELOPER MAINTENANCE & MODIFICATION GUIDE
 * - What can be changed: Add new character set mapping tables, add larger
 *   font sizes (8x16, etc.), add .CHR vector font parsing.
 * - What cannot be changed: The CP437 glyph data format (8 bytes per glyph).
 * - What to expect: BGI_outtextxy() renders left-to-right at the given coords.
 * - What to do if something breaks: Verify font glyph index is in range.
 *
 * SECTION 3: ASSUMPTIONS & PORTABILITY CONCERNS
 * - Assumptions: Characters are 7-bit ASCII (0-127 commonly used).
 * - Portability concerns: Pure ISO C17. No OS dependencies.
 *
 * SECTION 4: FUTURE EXPANSIONS & EXTENSION HOOKS
 * - How future expansion can occur safely: Add BGI_settextstyle() support for
 *   multiple font faces, vertical text, and magnification > 1.
 * - How to write external extensions: Provide a font_data pointer and
 *   cell_w/cell_h in the BGI_VideoMode descriptor.
 */

